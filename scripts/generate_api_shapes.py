"""Regenerates docs/api-shapes.md from the card dataclasses."""
import dataclasses
import importlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from cardModels.Card import Card

for module in sorted((ROOT / "cardModels").glob("*.py")):
    if module.stem != "__init__":
        importlib.import_module(f"cardModels.{module.stem}")


def type_name(field):
    return field.type if isinstance(field.type, str) else field.type.__name__


def describe(cls, inherited_from=None):
    lines = [f"## {cls.__name__}", ""]
    if cls.__doc__ and not cls.__doc__.startswith(cls.__name__):
        lines += [cls.__doc__.strip(), ""]
    lines += ["| Field | Type | Declared on |", "|---|---|---|"]
    for field in dataclasses.fields(cls):
        owner = next(k.__name__ for k in reversed(cls.__mro__)
                     if dataclasses.is_dataclass(k) and field.name in k.__annotations__)
        lines.append(f"| `{field.name}` | `{type_name(field)}` | {owner} |")
    lines.append("")
    return lines


out = [
    "# API Shapes",
    "",
    "Field reference for the card data objects.",
    "",
    "Generated by `scripts/generate_api_shapes.py` — do not edit by hand.",
    "",
]
for cls in [Card, *Card.__subclasses__()]:
    out += describe(cls)

out += [
    "## Construction",
    "",
    "All card classes are `@dataclass(kw_only=True)`, so they cannot be built positionally.",
    "`kw_only` is not inherited — a new `Card` subclass needs its own decorator argument.",
    "",
]

target = ROOT / "docs" / "api-shapes.md"
target.write_text("\n".join(out))
print(f"wrote {target.relative_to(ROOT)}")
